import { defineSlotRecipe } from '@pandacss/dev';
import { column, ruleAbove } from '../fragments';
import { currentFill, hoverSurface } from '../interaction';
import type { TypeSystem } from '../type-scale';

/** The audio player: a fixed bar with transport, seek and volume, and a queue panel that opens above it. */
export const player = (t: TypeSystem) => {
  const textSize = t.textSize;
  return defineSlotRecipe({
    className: 'player',
    slots: [
      'panel',
      'panelHead',
      'queue',
      'row',
      'grip',
      'rowTitle',
      'rowMeta',
      'permalink',
      'bar',
      'now',
      'nowTitle',
      'nowArtist',
      'nowError',
      'controls',
      'seek',
      'time',
      'options',
      'volume',
    ],
    base: {
      panel: {
        ...column,
        position: 'fixed',
        insetInline: '0',
        bottom: 'token(sizes.player)',
        maxHeight: 'panel',
        background: 'gray.2',
        color: 'fg.default',
        ...ruleAbove,
        zIndex: 'sticky',
      },
      panelHead: {
        display: 'flex',
        alignItems: 'center',
        gap: '4',
        paddingBlock: '2',
        paddingInline: '4',
      },
      queue: { ...column, overflowY: 'auto', paddingInline: '4', paddingBlockEnd: '2' },
      row: {
        display: 'flex',
        alignItems: 'center',
        gap: '2',
        paddingBlock: '1',
        borderBlockStartWidth: 'rail',
        borderColor: 'transparent',
        contentVisibility: 'auto',
        containIntrinsicSize: '0 token(sizes.8)',
        cursor: 'grab',
        ...hoverSurface,
        '&[data-current="true"]': currentFill,
        '&[data-over="true"]': { borderColor: 'accent' },
      },
      grip: { color: 'fg.subtle' },
      rowTitle: { flex: '1', textAlign: 'start', cursor: 'pointer' },
      rowMeta: { color: 'fg.muted' },
      permalink: { flex: '1' },
      bar: {
        position: 'fixed',
        insetInline: '0',
        bottom: '0',
        height: 'player',
        display: 'flex',
        alignItems: 'center',
        gap: '6',
        paddingInline: '4',
        background: 'gray.1',
        ...ruleAbove,
        zIndex: 'banner',
      },
      now: { maxWidth: 'now', minWidth: '0' },
      nowTitle: { ...textSize('body', 'sm'), color: 'fg.default' },
      nowArtist: { ...textSize('body', 'xs'), color: 'fg.muted' },
      nowError: { ...textSize('body', 'xs'), color: 'error' },
      controls: { display: 'flex', alignItems: 'center', gap: '4' },
      seek: { flex: '1', display: 'flex', alignItems: 'center', gap: '2' },
      time: { ...textSize('body', 'xs'), color: 'fg.muted' },
      options: { display: 'flex', alignItems: 'center', gap: '2' },
      volume: { width: 'slider' },
    },
  });
};
